package llm

import (
	"context"
	"rag-course/config"
	"strings"

	"github.com/openai/openai-go/v3"
	"github.com/openai/openai-go/v3/option"
)

// One entry in a chat conversation
type Message struct {
	Role    string `json:"role"`    // system, user, or assistant
	Content string `json:"content"` // text payload. We can also use custom type for content from the SDK provided by OpenAI
	// like chat.completion.message.param in the SDK provided by OpenAI.
}

type Client struct {
	cfg config.Config
	sdk openai.Client
}

// Factory function
func New(cfg config.Config) *Client {
	return newClient(cfg, cfg.BaseURL, cfg.APIKey)
}

func NewEmbedder(cfg config.Config) *Client {
	return newClient(cfg, cfg.EmbeddingBaseURL, cfg.EmbeddingAPIKey)
}

func newClient(cfg config.Config, baseURL, apiKey string) *Client {
	opts := []option.RequestOption{}
	if baseURL != "" {
		opts = append(opts, option.WithBaseURL(cfg.BaseURL))
	}
	if apiKey != "" {
		opts = append(opts, option.WithAPIKey(cfg.APIKey))
	}

	return &Client{
		cfg: cfg,
		sdk: openai.NewClient(opts...),
	}
}

// Open a streaming chat completion request with the OpenAI API, invoking the onDelta callback for each partial response.
func (c *Client) ChatStream(ctx context.Context, messages []Message, onDelta func(string)) (Message, error) {
	stream := c.sdk.Chat.Completions.NewStreaming(ctx, openai.ChatCompletionNewParams{
		Model:    c.cfg.Model,
		Messages: toSDKMessages(messages),
	}) // Streaming messages from the OpenAI API are received ordered incrementally in the client
	defer stream.Close() // properly close the stream when done to prevent resource leakage

	var content strings.Builder
	role := "assistant"

	for stream.Next() {
		chunk := stream.Current()
		if len(chunk.Choices) == 0 {
			continue
		}
		delta := chunk.Choices[0].Delta // In out case, we are always going to get only one choice per chunk
		// because we did not specify the response type or the number of choices, the API defaults to a single
		// choice per chunk.

		if delta.Role != "" {
			role = delta.Role
		}

		// Skip empty content chunks (usually the first chunk in the stream has no content)
		if delta.Content != "" {
			content.WriteString(delta.Content) // append content to the accumulated response
			// onDelta is called for each partial content chunk received from the stream. It is a callback for
			// real-time updates as the content is being generated by the OpenAI API.
			if onDelta != nil {
				onDelta(delta.Content)
			}
		}
	}

	if err := stream.Err(); err != nil {
		return Message{}, err
	}

	return Message{
		Role:    role,
		Content: content.String(),
	}, nil
}

// Function to convert prepared request messages to the SDK-specific message format used by the OpenAI Go SDK.
func toSDKMessages(messages []Message) []openai.ChatCompletionMessageParamUnion {
	out := make([]openai.ChatCompletionMessageParamUnion, 0, len(messages))
	for _, msg := range messages {
		switch msg.Role {
		case "system":
			out = append(out, openai.SystemMessage(msg.Content))
		case "assistant":
			out = append(out, openai.AssistantMessage(msg.Content))
		default:
			out = append(out, openai.UserMessage(msg.Content))
		}
	}

	return out
}
